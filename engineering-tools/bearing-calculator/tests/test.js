"use strict";
const assert=require("node:assert/strict");
const {calculate}=require("../js/bearing-engine.js");
function close(actual,expected,tol,label){assert.ok(Math.abs(actual-expected)<=tol, label+": expected "+expected+", got "+actual);}
const skfLow=calculate({method:"spherical",Fr:11121,Fa:2224,e:.22,Y1:3,Y2:4.6,C:210000,C0:0,n:2000,p:10/3,a1:1,targetLife:0,X0:0,Y0:0});
close(skfLow.P,17793,.001,"SKF case 1 equivalent load");
close(skfLow.L10h,31192.6645,.01,"SKF case 1 recomputed ISO life");
const skfHigh=calculate({method:"spherical",Fr:11121,Fa:2667,e:.22,Y1:3,Y2:4.6,C:210000,C0:120000,n:2000,p:10/3,a1:1,targetLife:0,X0:.6,Y0:.5});
close(skfHigh.P,19719.27,.001,"SKF case 2 equivalent load");
close(skfHigh.L10h,22143.5353,.01,"SKF case 2 recomputed ISO life");
const feu=calculate({method:"xy",Fr:5000,Fa:0,X:1,Y:0,X0:1,Y0:0,C:20000,C0:0,n:1000,p:3,a1:1,targetLife:1066.6666667});
close(feu.L10,64,1e-10,"FeuTex L10");
close(feu.L10h,1066.6666667,1e-5,"FeuTex L10h");
assert.throws(()=>calculate({method:"xy",Fr:1,Fa:0,X:1,Y:0,X0:1,Y0:0,C:0,C0:1,n:1000,p:3,a1:1,targetLife:100}),/greater than zero/);
assert.throws(()=>calculate({method:"axial",Fr:5,Fa:10,C:100,C0:100,n:1000,p:3,a1:1,targetLife:100}),/requires Fr = 0/);
const drawingDims={id:25,od:52,width:15};
assert.ok(drawingDims.od>drawingDims.id,"OD must exceed ID");
assert.ok(drawingDims.width>0,"Bearing width must be positive");
assert.ok(Math.abs((drawingDims.id+drawingDims.od)/2-38.5)<1e-12,"Mean diameter calculation");
assert.ok(Math.abs((210000/17793)**(10/3)*1e6/(60*2000)-31192.6645)<.01,"Independent life equation benchmark");
const ranges={id:{min:20,max:25},od:{min:45,max:55},width:{min:12,max:18}};
assert.equal(require("../js/bearing-engine.js").matchesDimensions({id:20,od:45,width:12},ranges),true,"inclusive minimum boundaries");
assert.equal(require("../js/bearing-engine.js").matchesDimensions({id:25,od:55,width:18},ranges),true,"inclusive maximum boundaries");
assert.equal(require("../js/bearing-engine.js").matchesDimensions({id:25.01,od:52,width:15},ranges),false,"ID above maximum rejected");
assert.equal(require("../js/bearing-engine.js").matchesDimensions({id:22,od:55.01,width:15},ranges),false,"OD above maximum rejected");
assert.equal(require("../js/bearing-engine.js").matchesDimensions({id:22,od:52,width:11.99},ranges),false,"width below minimum rejected");
assert.throws(()=>require("../js/bearing-engine.js").validateDimensionRanges({id:{min:25,max:20},od:{min:40,max:50},width:{min:10,max:15}}),/Minimum ID cannot exceed maximum ID/);
assert.throws(()=>require("../js/bearing-engine.js").validateDimensionRanges({id:{min:0,max:20},od:{min:40,max:50},width:{min:10,max:15}}),/positive minimum and maximum/);
console.log("PASS: 19 bearing calculation, geometry-input and independent equation assertions.");
console.log("NOTE: SKF published example 1 reports 33,400 h; its stated inputs/equation recompute to 31,192.66 h. This discrepancy is intentionally not masked.");
